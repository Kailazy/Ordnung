/// One column of the track table. The cover thumbnail plus the data columns
/// are reorderable and show/hideable from the header's right-click menu; the
/// chosen order and hidden set persist to `~/.ordnung/config.toml`. The trailing
/// `remainder` spacer is structural (it just fills slack so the striped rows span
/// the full width) and is intentionally not represented here.
#[derive(Clone, Copy, PartialEq, Eq, Hash)]
enum TableColumn {
    Cover,
    /// Inline colored waveform thumbnail (like Serato/rekordbox). Not sortable;
    /// painted from the row's `waveform`/`waveform_bands`, colored per the
    /// `waveform_color_mode` setting.
    Waveform,
    Artist,
    Title,
    Album,
    Genre,
    Duration,
    /// Detected/tagged tempo in BPM (`tracks.bpm_tag`), shown to two decimals.
    Bpm,
    Key,
    Format,
    Bitrate,
    Quality,
    /// Free-text notes — the file's comment tag (ID3 COMM / Vorbis COMMENT),
    /// surfaced read-only here. See `Tags::comment` in ordnung-core.
    Notes,
    /// When the track was first scanned into the catalog (`tracks.added_at`),
    /// shown as a relative age ("today", "3d ago"). Sort it descending to see
    /// the most recent import at the top.
    Added,
}

impl TableColumn {
    /// Every column in the default left-to-right order. Doubles as the source of
    /// truth for "which columns exist": the reorder menu lists these, and loading
    /// a saved layout appends any column missing from it (so a config written by
    /// an older build still shows columns added since).
    const DEFAULT_ORDER: [TableColumn; 14] = [
        TableColumn::Cover,
        TableColumn::Artist,
        TableColumn::Title,
        TableColumn::Album,
        TableColumn::Genre,
        TableColumn::Duration,
        TableColumn::Waveform,
        TableColumn::Added,
        TableColumn::Bpm,
        TableColumn::Key,
        TableColumn::Format,
        TableColumn::Bitrate,
        TableColumn::Quality,
        TableColumn::Notes,
    ];

    /// Stable key persisted to config — deliberately independent of the enum
    /// order and the display label so reordering the enum or renaming a header
    /// can't corrupt a saved layout.
    fn key(self) -> &'static str {
        match self {
            TableColumn::Cover => "cover",
            TableColumn::Waveform => "waveform",
            TableColumn::Artist => "artist",
            TableColumn::Title => "title",
            TableColumn::Album => "album",
            TableColumn::Genre => "genre",
            TableColumn::Duration => "duration",
            TableColumn::Bpm => "bpm",
            TableColumn::Key => "key",
            TableColumn::Format => "format",
            TableColumn::Bitrate => "bitrate",
            TableColumn::Quality => "quality",
            TableColumn::Notes => "notes",
            TableColumn::Added => "added",
        }
    }

    /// Parse a persisted key back into a column, ignoring anything unknown (a key
    /// from a newer build, or a typo'd hand-edited config).
    fn from_key(s: &str) -> Option<TableColumn> {
        TableColumn::DEFAULT_ORDER
            .into_iter()
            .find(|c| c.key() == s)
    }

    /// Display name: the header text, and the row label in the reorder menu. The
    /// cover header draws no text, but the column still needs a name in the menu.
    fn label(self) -> &'static str {
        match self {
            TableColumn::Cover => "Cover",
            TableColumn::Waveform => "Wave",
            TableColumn::Artist => "Artist",
            TableColumn::Title => "Title",
            TableColumn::Album => "Album",
            TableColumn::Genre => "Genre",
            TableColumn::Duration => "Dur",
            TableColumn::Bpm => "BPM",
            TableColumn::Key => "Key",
            TableColumn::Format => "Format",
            TableColumn::Bitrate => "kbps",
            TableColumn::Quality => "Qual",
            TableColumn::Notes => "Notes",
            TableColumn::Added => "Added",
        }
    }

    /// The sort key cycled by clicking this header, or `None` for the (unsortable)
    /// cover column.
    fn sort_column(self) -> Option<SortColumn> {
        Some(match self {
            TableColumn::Cover => return None,
            TableColumn::Waveform => return None,
            TableColumn::Artist => SortColumn::Artist,
            TableColumn::Title => SortColumn::Title,
            TableColumn::Album => SortColumn::Album,
            TableColumn::Genre => SortColumn::Genre,
            TableColumn::Duration => SortColumn::Duration,
            TableColumn::Bpm => SortColumn::Bpm,
            TableColumn::Key => SortColumn::Key,
            TableColumn::Format => SortColumn::Format,
            TableColumn::Bitrate => SortColumn::Bitrate,
            TableColumn::Quality => SortColumn::Quality,
            TableColumn::Notes => SortColumn::Notes,
            TableColumn::Added => SortColumn::Added,
        })
    }

    /// The narrowest this column may be dragged. Also the floor for the
    /// right-edge cap in `spec`: a column can always reach its minimum even in a
    /// window too narrow to hold it.
    fn min_width(self, cover_px: f32) -> f32 {
        match self {
            TableColumn::Cover => cover_px + 6.0,
            TableColumn::Waveform => 60.0,
            TableColumn::Artist => 80.0,
            TableColumn::Title => 80.0,
            TableColumn::Album => 60.0,
            TableColumn::Genre => 60.0,
            TableColumn::Duration => 40.0,
            TableColumn::Bpm => 56.0,
            TableColumn::Key => 40.0,
            TableColumn::Format => 50.0,
            TableColumn::Bitrate => 50.0,
            TableColumn::Quality => 48.0,
            TableColumn::Notes => 80.0,
            TableColumn::Added => 60.0,
        }
    }

    /// This column's default width, used before the user has resized it (and by
    /// the table to lay out the right-edge drag cap on the first frame, when no
    /// measured width exists yet).
    fn default_width(self, cover_px: f32) -> f32 {
        match self {
            TableColumn::Cover => cover_px + 6.0,
            TableColumn::Waveform => 140.0,
            TableColumn::Artist => 180.0,
            TableColumn::Title => 260.0,
            TableColumn::Album => 180.0,
            TableColumn::Genre => 110.0,
            TableColumn::Duration => 60.0,
            TableColumn::Bpm => 74.0,
            TableColumn::Key => 55.0,
            TableColumn::Format => 60.0,
            TableColumn::Bitrate => 70.0,
            TableColumn::Quality => 66.0,
            TableColumn::Notes => 200.0,
            TableColumn::Added => 90.0,
        }
    }

    /// This column's egui_extras width spec (the same sizes the table used when
    /// columns were hard-coded). `cover_px` is the thumbnail edge length.
    /// `width` overrides the initial width with the user's saved value (see
    /// `App::column_widths`); `None` uses the per-column default. `max` caps how
    /// wide it may be dragged — the caller passes the space left before the
    /// table's right edge, so a resize can never push the column's own edge (and
    /// its drag handle) off screen. The Cover column is a fixed size and ignores
    /// both.
    fn spec(self, cover_px: f32, width: Option<f32>, max: Option<f32>) -> Column {
        if self == TableColumn::Cover {
            return Column::exact(cover_px + 6.0);
        }
        let min = self.min_width(cover_px);
        let col = Column::initial(width.unwrap_or_else(|| self.default_width(cover_px)))
            .at_least(min)
            .clip(self.clips());
        // Never cap below the minimum: a very narrow window must still leave the
        // column draggable within its own legal range.
        match max {
            Some(m) => col.at_most(m.max(min)),
            None => col,
        }
    }

    /// Whether this column clips its content rather than forcing itself wider.
    /// The free-text columns clip; the short numeric ones don't. Waveform stays
    /// unclipped because when it leads the row its paint stretches left across the
    /// blank order gutter (see the flush-left rect in table.rs), which a cell clip
    /// would cut off.
    fn clips(self) -> bool {
        matches!(
            self,
            TableColumn::Artist
                | TableColumn::Title
                | TableColumn::Album
                | TableColumn::Genre
                | TableColumn::Notes
        )
    }
}

