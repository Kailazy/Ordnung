/// One device file's BPM/key as analyzed by Ordnung's own engine — the
/// automatic fallback for USB rows where neither the stick's `export.pdb` nor
/// the file's tags carry them. Never written anywhere: device files aren't
/// catalog rows, so this lives only in `App::usb_analysis` for the session.
#[derive(Debug, Clone)]
struct UsbAnalyzed {
    path: String,
    bpm: Option<f32>,
    key: Option<ordnung_core::model::key::Key>,
    /// Analyzer waveforms for sticks whose ANLZ files carry none — so device
    /// rows draw like library rows either way.
    waveform: Vec<u8>,
    waveform_bands: Vec<u8>,
}

/// USB tracks aren't catalog rows, but the shared table needs an `Id` per row.
/// Synthesize ids far above any real SQLite rowid so the two spaces can never
/// collide; catalog lookups on these simply miss (no analysis, no covers).
const USB_ID_BASE: Id = 1 << 62;

fn usb_track_id(index: usize) -> Id {
    USB_ID_BASE + index as Id
}

/// Inverse of [`usb_track_id`]: the `usb_tracks` index behind a synthetic id.
fn usb_track_index(id: Id) -> Option<usize> {
    id.checked_sub(USB_ID_BASE).map(|i| i as usize)
}

