/// Messages the worker thread can send back to the UI.
enum JobMsg {
    Status(String),
    /// Determinate progress for the running job: `done` of `total` items
    /// finished. Drives the status-bar progress bar.
    Progress {
        done: usize,
        total: usize,
    },
    Done(String),
    Failed(String),
    /// Per-item failures from a background job: `(item name, reason)`, with a
    /// `title` naming what was attempted (e.g. "Scan", "Write edits"). Sent just
    /// before `Done` whenever a job skipped or errored on any item, so the UI
    /// can show the user exactly what didn't go through and why.
    Failures {
        title: String,
        items: Vec<(String, String)>,
    },
    /// Candidate releases fetched for one track, for the user to pick from.
    ArtworkChoices(ArtworkChoices),
    /// The Discogs username resolved during a vinyl sync, so the UI can persist
    /// it (config) and link to the user's collection page.
    VinylUsername(String),
}

/// Result of a background full-resolution cover load. The decode (potentially a
/// multi-megapixel JPEG) happens off the UI thread; the main thread turns the
/// pixels into a texture. `image` is `None` when the track has no usable cover.
struct CoverLoaded {
    id: Id,
    image: Option<egui::ColorImage>,
    /// Set only for USB loads: the device listing the request was made against.
    /// `None` from the catalog loader, whose ids are stable rowids.
    usb_generation: Option<u64>,
}

/// Where a USB row's cover art comes from. Resolved on the UI thread (a map
/// lookup) and handed to the loader, so the worker never reaches into `App`
/// state that the UI thread is concurrently mutating.
enum UsbThumbSource {
    /// The file scan already extracted the embedded art.
    Embedded(Vec<u8>),
    /// Nothing scanned yet: the export's pre-extracted ARTWORK JPEG on the
    /// device stands in. This is the read that has to stay off the UI thread —
    /// it hits the stick.
    File(PathBuf),
}

/// One USB cover to load, with its source already resolved.
struct UsbThumbReq {
    id: Id,
    source: UsbThumbSource,
    /// Which device listing this was asked for. USB ids are `BASE + index`, so
    /// index 5 on the next stick reuses index 5's id on this one — without this
    /// an in-flight decode could land on an unrelated row after a swap.
    generation: u64,
}

/// Identity of one vinyl cover: which Discogs list it belongs to and that list's
/// row key (`instance_id` for the collection, `release_id` for the wantlist).
type VinylCoverKey = (VinylList, u64);

/// Result of a background vinyl cover decode, carrying the key that asked for it
/// so the collection and wantlist grids never cross wires.
struct VinylCoverLoaded {
    key: VinylCoverKey,
    image: Option<egui::ColorImage>,
}

/// One user-requested change to a Discogs list. Every variant writes to the
/// user's actual Discogs account and then mirrors the change into the local
/// cache, so the grid reflects it without waiting for a full sync. Built by the
/// vinyl grid's right-click menu and the library's "Add to Discogs wantlist",
/// then run off the UI thread by `run_vinyl_edit`.
#[derive(Debug, Clone)]
pub(crate) enum VinylEdit {
    /// Want these releases, named from the library rather than the grid — so
    /// there's no cached record yet and Discogs's response supplies the metadata.
    /// Carries a label for the status line, since the ids mean nothing to the user.
    Want {
        release_ids: Vec<u64>,
        label: String,
    },
    /// Move one cached record to the other list. Two Discogs calls (add to the
    /// destination, remove from the source), then one local re-key.
    Move {
        from: VinylList,
        record: Box<VinylRecord>,
    },
    /// Own one release, named by id rather than from a cached row — the record
    /// sheet's "Add to collection", which can be open on a record the user
    /// doesn't have yet (a dug one). Mirrors [`VinylEdit::Want`]: Discogs's
    /// response supplies the metadata to cache.
    Collect { release_id: u64, label: String },
    /// Drop one cached record from its list entirely.
    Remove {
        list: VinylList,
        record: Box<VinylRecord>,
    },
    /// Replace one cached record with a different pressing of the same record —
    /// the "hotswap" from the versions panel. Structurally a [`VinylEdit::Move`]
    /// that changes release rather than list: add `to_release` to the list the
    /// record is already in, then drop the old copy. Ordered that way so a
    /// failure leaves the user with both pressings rather than neither.
    Swap {
        list: VinylList,
        record: Box<VinylRecord>,
        to_release: u64,
        /// How to name the incoming pressing in the status line, since its id
        /// means nothing to the user.
        to_label: String,
    },
}

impl VinylEdit {
    /// Whether this edit destroys a collection copy on Discogs — its date added,
    /// rating and notes go with it, and Ordnung can't put them back. True for
    /// both an outright removal from the collection and a move out of it; those
    /// are the edits worth a confirmation step. Wantlist edits are cheap to undo
    /// (re-adding a want costs nothing but the release id), so they just run.
    pub(crate) fn destroys_collection_copy(&self) -> bool {
        matches!(
            self,
            VinylEdit::Move {
                from: VinylList::Collection,
                ..
            } | VinylEdit::Remove {
                list: VinylList::Collection,
                ..
            } | VinylEdit::Swap {
                list: VinylList::Collection,
                ..
            }
        )
    }
}

/// Result of a background "what would this release fill in?" lookup, computed for
/// the "Fetch song data" picker so the user can see the data before committing.
/// Carries the human-readable (field, value) rows to display and the underlying
/// `ReleaseDetail` to reuse on apply (so we don't fetch the release twice).
struct PreviewMsg {
    track_id: Id,
    release_id: String,
    /// Whether this preview was computed in overwrite mode — part of the cache
    /// key, so it must round-trip back from the worker.
    overwrite: bool,
    /// `(field label, value)` for each field this release would write under the
    /// current mode. Empty when the release adds nothing new or the lookup failed.
    fills: Vec<(String, String)>,
    /// `None` when the release lookup failed (network/decode).
    detail: Option<discogs::ReleaseDetail>,
}

/// What the Discogs settings tab knows about the saved token. "Connected" is
/// only ever reached by a real `GET /oauth/identity` round-trip — a token that
/// merely *exists* in the config proves nothing, since it may have been revoked
/// or mistyped, and the old UI surfaced that as a confusing mid-fetch failure.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub(crate) enum DiscogsAuth {
    /// No token saved (and none in `DISCOGS_TOKEN`).
    #[default]
    SignedOut,
    /// A token is saved but hasn't been checked yet this session.
    Unverified,
    /// Identity request in flight.
    Checking,
    /// Discogs confirmed the token and named its owner.
    Connected { username: String },
    /// Discogs rejected the token (HTTP 401/403) — revoked, mistyped, or wrong.
    Rejected,
    /// The check itself failed (offline, DNS, timeout). Distinct from
    /// [`DiscogsAuth::Rejected`]: the token may be perfectly good, so this must
    /// not read as "your token is bad".
    Unreachable { detail: String },
}

